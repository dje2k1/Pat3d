"""texlib — shared helpers for Kit Rush 3D's generated PBR textures (SPEC3 §4).

Every texture of the game is generated by our own code (numpy + Pillow, no scipy, no downloaded art). Each art role
owns tools/tex/<role>_*.py scripts and the folder assets/tex/<role>/ with its own manifest.json (merged by K.tex at
runtime, so roles never edit a shared file).

Conventions
- Images are float32 numpy arrays in 0..1, shape (H, W) for one channel or (H, W, C).
- Everything tiles: noise is periodic over the image (pass the period in cells), blurs and samplers wrap around.
- Normal maps: tangent space, OpenGL convention (+Y up = green up), encoded n * 0.5 + 0.5.
- ORM: R = ambient occlusion, G = roughness, B = metalness (glTF order), linear data.
- Albedo is authored in sRGB (what you see is what is stored); normal / ORM / masks are linear data.
- 'full' (1024 or 2048) and 'half' (half size) sets; the manifest records both (K.tex picks one from K.gfx.texRes).

Typical script (tools/tex/world_grass.py):

    import sys, os; sys.path.insert(0, os.path.dirname(__file__))
    from texlib import *
    m = Manifest('world')
    N = 1024
    h = fbm(N, 8, octaves=6, seed=3)                       # tiling height field
    albedo = colorize(h, [(0, '#2f7d32'), (1, '#7bd44a')])
    m.add('grass_albedo', albedo, colorspace='srgb', group='act1')
    m.add('grass_normal', height_to_normal(h, strength=4), colorspace='linear', group='act1')
    m.add('grass_orm', orm(ao=cavity_ao(h), rough=0.85 + 0.1 * h, metal=0), colorspace='linear', group='act1')
    m.save()

Run it with `python3 tools/tex/world_grass.py`; it writes assets/tex/world/grass_albedo.webp, grass_albedo_half.webp,
... and merges the entries into assets/tex/world/manifest.json (entries of other scripts of the same role are kept).
"""
import json
import math
import os

import numpy as np
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
ASSETS = os.path.join(ROOT, 'assets', 'tex')


# --------------------------------------------------------------------------------------------- random / hashing
def rng(seed):
    return np.random.default_rng(seed)


# --------------------------------------------------------------------------------------------- sampling helpers
def _smooth(t):
    return t * t * t * (t * (t * 6 - 15) + 10)  # quintic fade


def sample_wrap(img, x, y):
    """Bilinear sample of img (H, W[, C]) at float pixel coordinates x, y (arrays), wrapping around."""
    H, W = img.shape[:2]
    x0 = np.floor(x).astype(np.int64)
    y0 = np.floor(y).astype(np.int64)
    fx = (x - x0)
    fy = (y - y0)
    x0 %= W
    y0 %= H
    x1 = (x0 + 1) % W
    y1 = (y0 + 1) % H
    if img.ndim == 3:
        fx = fx[..., None]
        fy = fy[..., None]
    a = img[y0, x0]
    b = img[y0, x1]
    c = img[y1, x0]
    d = img[y1, x1]
    return (a * (1 - fx) + b * fx) * (1 - fy) + (c * (1 - fx) + d * fx) * fy


def grid(n, m=None):
    """Pixel-centre coordinates in 0..1 for an n x m image: returns (u, v) arrays of shape (m, n)."""
    m = m or n
    u = (np.arange(n, dtype=np.float32) + 0.5) / n
    v = (np.arange(m, dtype=np.float32) + 0.5) / m
    return np.meshgrid(u, v)


# --------------------------------------------------------------------------------------------- tiling noise
def value_noise(n, period, seed=0, m=None):
    """Periodic value noise: n x m image, `period` lattice cells across (int), 0..1."""
    m = m or n
    r = rng(seed)
    pm = max(1, int(round(period * m / n)))
    lat = r.random((pm, period), dtype=np.float32)
    u, v = grid(n, m)
    return sample_smooth(lat, u * period, v * pm)


def sample_smooth(lat, x, y):
    """Smooth (quintic) interpolation of a periodic lattice at lattice coordinates x, y."""
    H, W = lat.shape
    x0 = np.floor(x).astype(np.int64)
    y0 = np.floor(y).astype(np.int64)
    fx = _smooth(x - x0)
    fy = _smooth(y - y0)
    x0 %= W
    y0 %= H
    x1 = (x0 + 1) % W
    y1 = (y0 + 1) % H
    a = lat[y0, x0]
    b = lat[y0, x1]
    c = lat[y1, x0]
    d = lat[y1, x1]
    return ((a * (1 - fx) + b * fx) * (1 - fy) + (c * (1 - fx) + d * fx) * fy).astype(np.float32)


def gradient_noise(n, period, seed=0, m=None):
    """Periodic gradient (Perlin) noise, 0..1 (0.5 mean)."""
    m = m or n
    r = rng(seed)
    pm = max(1, int(round(period * m / n)))
    ang = r.random((pm, period)) * 2 * math.pi
    gx = np.cos(ang).astype(np.float32)
    gy = np.sin(ang).astype(np.float32)
    u, v = grid(n, m)
    x = u * period
    y = v * pm
    x0 = np.floor(x).astype(np.int64)
    y0 = np.floor(y).astype(np.int64)
    fx = x - x0
    fy = y - y0
    out = np.zeros_like(x, dtype=np.float32)
    w = []
    for dy in (0, 1):
        for dx in (0, 1):
            ix = (x0 + dx) % period
            iy = (y0 + dy) % pm
            dot = gx[iy, ix] * (fx - dx) + gy[iy, ix] * (fy - dy)
            w.append(dot)
    sx = _smooth(fx)
    sy = _smooth(fy)
    out = (w[0] * (1 - sx) + w[1] * sx) * (1 - sy) + (w[2] * (1 - sx) + w[3] * sx) * sy
    return np.clip(out * 0.7071 + 0.5, 0, 1).astype(np.float32)


def worley(n, cells, seed=0, m=None, metric='euclid'):
    """Periodic cellular noise: returns (F1, F2, cell_id) with distances in cell units (F1 ~ 0..0.8)."""
    m = m or n
    r = rng(seed)
    cm = max(1, int(round(cells * m / n)))
    pts = r.random((cm, cells, 2)).astype(np.float32)
    ids = r.random((cm, cells)).astype(np.float32)
    u, v = grid(n, m)
    x = u * cells
    y = v * cm
    cx = np.floor(x).astype(np.int64)
    cy = np.floor(y).astype(np.int64)
    f1 = np.full(x.shape, 9.0, np.float32)
    f2 = np.full(x.shape, 9.0, np.float32)
    cid = np.zeros(x.shape, np.float32)
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            ix = cx + dx
            iy = cy + dy
            p = pts[iy % cm, ix % cells]
            px = ix + p[..., 0] - x
            py = iy + p[..., 1] - y
            if metric == 'manhattan':
                d = np.abs(px) + np.abs(py)
            elif metric == 'cheb':
                d = np.maximum(np.abs(px), np.abs(py))
            else:
                d = np.sqrt(px * px + py * py)
            closer = d < f1
            f2 = np.where(closer, f1, np.minimum(f2, d))
            cid = np.where(closer, ids[iy % cm, ix % cells], cid)
            f1 = np.where(closer, d, f1)
    return f1, f2, cid


def fbm(n, period, octaves=5, seed=0, lacunarity=2, gain=0.5, kind='value', m=None):
    """Fractal sum of periodic noise (period doubles each octave, so it still tiles), normalised 0..1."""
    f = value_noise if kind == 'value' else gradient_noise
    out = np.zeros((m or n, n), np.float32)
    amp = 1.0
    tot = 0.0
    p = period
    for o in range(octaves):
        out += f(n, int(p), seed + o * 101, m) * amp
        tot += amp
        amp *= gain
        p *= lacunarity
    return out / tot


def ridged(n, period, octaves=5, seed=0, m=None):
    """Ridged fbm (sharp crests), 0..1."""
    out = np.zeros((m or n, n), np.float32)
    amp = 1.0
    tot = 0.0
    p = period
    for o in range(octaves):
        g = 1 - np.abs(gradient_noise(n, int(p), seed + o * 57, m) * 2 - 1)
        out += g * g * amp
        tot += amp
        amp *= 0.5
        p *= 2
    return out / tot


def domain_warp(img, wx, wy, amount):
    """Warps img by the displacement fields wx, wy (0..1, centred at 0.5) times amount (in pixels), wrapping."""
    H, W = img.shape[:2]
    y, x = np.mgrid[0:H, 0:W].astype(np.float32)
    return sample_wrap(img, x + (wx - 0.5) * 2 * amount, y + (wy - 0.5) * 2 * amount)


def blur(img, radius):
    """Separable box blur (3 passes ~ gaussian), wrapping. radius in pixels (int)."""
    radius = int(radius)
    if radius <= 0:
        return img
    out = img.astype(np.float32)
    for _ in range(3):
        for axis in (0, 1):
            acc = np.zeros_like(out)
            for k in range(-radius, radius + 1):
                acc += np.roll(out, k, axis=axis)
            out = acc / (2 * radius + 1)
    return out


# --------------------------------------------------------------------------------------------- shaping
def remap(x, a, b, c=0.0, d=1.0):
    return np.clip((x - a) / (b - a), 0, 1) * (d - c) + c


def smoothstep(a, b, x):
    t = np.clip((x - a) / (b - a), 0, 1)
    return t * t * (3 - 2 * t)


def hex_rgb(h):
    h = h.lstrip('#')
    return np.array([int(h[i:i + 2], 16) / 255.0 for i in (0, 2, 4)], np.float32)


def colorize(t, stops):
    """Maps a 0..1 field to sRGB colours through [(pos, '#rrggbb'), ...] (linear interpolation in sRGB)."""
    t = np.clip(t, 0, 1)
    pos = np.array([s[0] for s in stops], np.float32)
    cols = np.stack([hex_rgb(s[1]) if isinstance(s[1], str) else np.asarray(s[1], np.float32) for s in stops])
    out = np.empty(t.shape + (3,), np.float32)
    for c in range(3):
        out[..., c] = np.interp(t, pos, cols[:, c])
    return out


def srgb_to_linear(c):
    c = np.asarray(c, np.float32)
    return np.where(c <= 0.04045, c / 12.92, ((c + 0.055) / 1.055) ** 2.4)


def linear_to_srgb(c):
    c = np.clip(np.asarray(c, np.float32), 0, 1)
    return np.where(c <= 0.0031308, c * 12.92, 1.055 * c ** (1 / 2.4) - 0.055)


# --------------------------------------------------------------------------------------------- PBR maps
def height_to_normal(h, strength=2.0):
    """Tangent-space normal map from a tiling height field (0..1), OpenGL convention (+Y = green up).
    strength scales the slopes (height difference of 1 across one pixel = strength)."""
    dx = (np.roll(h, -1, axis=1) - np.roll(h, 1, axis=1)) * 0.5 * strength
    dy = (np.roll(h, -1, axis=0) - np.roll(h, 1, axis=0)) * 0.5 * strength
    # image rows go down while +Y (green) points up the texture: v grows upward after the flipY upload
    n = np.stack([-dx, dy, np.ones_like(h)], axis=-1)
    n /= np.linalg.norm(n, axis=-1, keepdims=True)
    return n * 0.5 + 0.5


def cavity_ao(h, radius=6, strength=1.6):
    """Cheap tiling ambient occlusion from a height field: darker where the surface is below its blurred surroundings."""
    d = blur(h, radius) - h
    return np.clip(1 - np.maximum(d, 0) * strength * 4, 0, 1)


def orm(ao=1.0, rough=0.8, metal=0.0, shape=None):
    """Packs ORM (R = AO, G = roughness, B = metalness) from scalars or arrays."""
    arrs = [a for a in (ao, rough, metal) if isinstance(a, np.ndarray)]
    shp = shape or (arrs[0].shape if arrs else (4, 4))
    f = lambda a: np.broadcast_to(np.asarray(a, np.float32), shp)
    return np.stack([f(ao), f(rough), f(metal)], axis=-1)


# --------------------------------------------------------------------------------------------- output
def to_u8(img):
    return (np.clip(img, 0, 1) * 255 + 0.5).astype(np.uint8)


def resize(img, size):
    """Box-filtered resize to (w, h) of a 0..1 float image (uses Pillow in 16-bit-ish precision via float mode)."""
    w, h = size
    if img.ndim == 2:
        return np.asarray(Image.fromarray(img.astype(np.float32), 'F').resize((w, h), Image.BOX), np.float32)
    chans = [np.asarray(Image.fromarray(img[..., c].astype(np.float32), 'F').resize((w, h), Image.BOX), np.float32) for c in range(img.shape[2])]
    return np.stack(chans, axis=-1)


def write_webp(path, img, quality=90, lossless=False):
    """Writes a 0..1 float image (H, W), (H, W, 3) or (H, W, 4) as WebP; returns the byte size."""
    a = to_u8(img)
    mode = 'L' if a.ndim == 2 else ('RGBA' if a.shape[2] == 4 else 'RGB')
    if mode == 'L':
        a = np.stack([a] * 3, axis=-1)
        mode = 'RGB'
    im = Image.fromarray(a, mode)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    im.save(path, 'WEBP', quality=quality, lossless=lossless, method=6, exact=True)
    return os.path.getsize(path)


class Manifest:
    """Per-role manifest writer: assets/tex/<role>/manifest.json, merged with what is already there.

    add(name, img, colorspace='srgb'|'linear', group='act1'|'act2'|'common'|'none', wrap='repeat'|'clamp'|'mirror',
        half=True, quality=90 (albedo) / 95 (data), lossless=False)
    writes <name>.webp (full) and <name>_half.webp (half size) and records:
      { full, half, size: [w, h], halfSize: [w, h], colorSpace, bytes, halfBytes, group, wrap }
    The runtime name is '<role>/<name>' (K.tex.load('world/grass_albedo')).
    """

    def __init__(self, role):
        self.role = role
        self.dir = os.path.join(ASSETS, role)
        self.path = os.path.join(self.dir, 'manifest.json')
        os.makedirs(self.dir, exist_ok=True)
        self.data = {'role': role, 'textures': {}}
        if os.path.exists(self.path):
            with open(self.path) as f:
                old = json.load(f)
            self.data['textures'].update(old.get('textures', {}))

    def add(self, name, img, colorspace='srgb', group='act1', wrap='repeat', half=True, quality=None, lossless=False):
        if colorspace not in ('srgb', 'linear'):
            raise ValueError('colorspace must be srgb or linear')
        q = quality if quality is not None else (90 if colorspace == 'srgb' else 95)
        H, W = img.shape[:2]
        full = name + '.webp'
        e = {'full': full, 'size': [W, H], 'colorSpace': colorspace, 'group': group, 'wrap': wrap}
        e['bytes'] = write_webp(os.path.join(self.dir, full), img, q, lossless)
        if half:
            hw, hh = max(1, W // 2), max(1, H // 2)
            hn = name + '_half.webp'
            small = resize(img, (hw, hh))
            if colorspace == 'linear' and img.ndim == 3 and img.shape[2] == 3 and 'normal' in name:
                n = small * 2 - 1
                n /= np.maximum(np.linalg.norm(n, axis=-1, keepdims=True), 1e-6)
                small = n * 0.5 + 0.5
            e['half'] = hn
            e['halfSize'] = [hw, hh]
            e['halfBytes'] = write_webp(os.path.join(self.dir, hn), small, q, lossless)
        self.data['textures'][name] = e
        return e

    def remove(self, name):
        e = self.data['textures'].pop(name, None)
        if e:
            for k in ('full', 'half'):
                p = os.path.join(self.dir, e.get(k, ''))
                if e.get(k) and os.path.exists(p):
                    os.remove(p)

    def save(self):
        self.data['textures'] = dict(sorted(self.data['textures'].items()))
        with open(self.path, 'w') as f:
            json.dump(self.data, f, indent=1)
            f.write('\n')
        tot = sum(e.get('bytes', 0) + e.get('halfBytes', 0) for e in self.data['textures'].values())
        print('%s: %d textures, %.2f MB on disk' % (self.path, len(self.data['textures']), tot / 1048576))
        return self.path
